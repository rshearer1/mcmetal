#!/usr/bin/env python3
"""Generate glprof: a GL call profiler that sits between the game (LWJGL) and the real GL library.

Usage: python3 -I gen_glprof.py gl.xml OUT.c [NAMES]

Every OpenGL command in gl.xml (core and extensions) gets a wrapper with the same name that counts the call,
times it on the CPU and adds one size figure (bytes uploaded, vertices drawn, sub-draws of a multi-draw, ...),
then calls the real function. NAMES (one per line, e.g. `nm -gU libmcmetal.dylib`) limits the wrappers to what
the real library exports: on macOS LWJGL looks functions up with dlsym, so a wrapper with no real function behind
it would look like a working entry point. tools/glprof_report.py turns two snapshots into a per-frame table.
"""
import sys
import xml.etree.ElementTree as ET

xml_path, out_path = sys.argv[1], sys.argv[2]
only = None
if len(sys.argv) > 3:
    only = {l.split()[-1].lstrip("_") for l in open(sys.argv[3]) if l.strip()}
root = ET.parse(xml_path).getroot()


def text_of(el):
    return " ".join("".join(el.itertext()).split())


cmds = []
for cmd in root.find("commands"):
    proto = cmd.find("proto")
    name = proto.find("name").text
    if not name.startswith("gl") or name.startswith(("glX", "glu")):
        continue
    if only is not None and name not in only:
        continue
    if "_cl_" in "".join(cmd.itertext()):  # OpenCL interop: no CL types here, and nothing in Minecraft uses it
        continue
    ret = "".join(proto.itertext())[: -len(name)].strip()
    params = [(text_of(p), p.find("name").text) for p in cmd.findall("param")]
    cmds.append((name, ret, params))
cmds.sort()

# the one size figure each call adds (an expression over its parameters); everything else adds 0
AUX = {}
for n in ("glBufferData", "glNamedBufferData", "glBufferSubData", "glNamedBufferSubData", "glBufferStorage",
          "glNamedBufferStorage"):
    AUX[n] = "size"
for n in ("glCopyBufferSubData", "glCopyNamedBufferSubData"):
    AUX[n] = "size"
for n in ("glMapBufferRange", "glMapNamedBufferRange", "glFlushMappedBufferRange", "glFlushMappedNamedBufferRange"):
    AUX[n] = "length"
for n in ("glTexImage2D", "glTexSubImage2D", "glTextureSubImage2D"):
    AUX[n] = "(long)width * height"
for n in ("glTexImage3D", "glTexSubImage3D", "glTextureSubImage3D"):
    AUX[n] = "(long)width * height * depth"
for n in ("glDrawArrays", "glDrawElements", "glDrawElementsBaseVertex", "glDrawRangeElements",
          "glDrawRangeElementsBaseVertex"):
    AUX[n] = "count"
for n in ("glDrawArraysInstanced", "glDrawElementsInstanced", "glDrawElementsInstancedBaseVertex",
          "glDrawArraysInstancedBaseInstance", "glDrawElementsInstancedBaseInstance",
          "glDrawElementsInstancedBaseVertexBaseInstance"):
    AUX[n] = "(long)count * instancecount"
for n in ("glMultiDrawArrays", "glMultiDrawElements", "glMultiDrawElementsBaseVertex", "glMultiDrawArraysIndirect",
          "glMultiDrawElementsIndirect"):
    AUX[n] = "drawcount"
AUX["glDispatchCompute"] = "(long)num_groups_x * num_groups_y * num_groups_z"
AUX["glBlitFramebuffer"] = "(long)(dstX1 - dstX0) * (dstY1 - dstY0)"
AUX["glReadPixels"] = "(long)width * height"
AUX["glGetTexImage"] = "1"


o = open(out_path, "w")
w = o.write
w('''/* Generated by gen_glprof.py. Do not edit. See tools/glprof.h for what this is and how to use it. */
#include "glprof.h"

''')
w("const char *const gp_names[] = {\n" + "".join(f'    "{n}",\n' for n, _, _ in cmds) + "};\n")
w(f"const int gp_count = {len(cmds)};\n")
w(f"gp_stat gp_stats[{len(cmds)}];\n\n")
for i, (n, ret, params) in enumerate(cmds):
    ptxt = ", ".join(p for p, _ in params) or "void"
    args = ", ".join(a for _, a in params)
    w(f"static {ret} (*real_{n})({ptxt});\n")
    w(f"GP_EXPORT {ret} {n}({ptxt})\n{{\n")
    w(f"    GP_REAL({n});\n    uint64_t gp_t0 = gp_now();\n")
    call = f"real_{n}({args})"
    aux = AUX.get(n, "0")
    if ret == "void":
        w(f"    {call};\n    gp_add({i}, gp_t0, {aux});\n")
    else:
        w(f"    {ret} r = {call};\n    gp_add({i}, gp_t0, {aux});\n    return r;\n")
    w("}\n\n")
# lookup by name for glXGetProcAddress (Linux): the wrapper, only if the real library has the function
w("void *gp_wrapper(const char *name)\n{\n")
for n, _, _ in cmds:
    w(f'    if (!strcmp(name, "{n}")) return gp_real("{n}") ? (void *){n} : NULL;\n')
w("    return NULL;\n}\n")
o.close()
print(f"glprof: {len(cmds)} wrappers")
