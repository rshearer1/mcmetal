#!/usr/bin/env python3
"""Generate the OpenGL entry points for libmcmetal from Khronos gl.xml.

Usage: python3 -I gen_exports.py gl.xml OUTDIR [VERSION]   (VERSION default 4.5)

Writes:
  OUTDIR/mgl_gl.h        GL types, enums used by the core profile, and prototypes
  OUTDIR/gl_stubs.c      one weak definition per core function: logs "unimplemented" once, returns 0
  OUTDIR/gl_functions.txt  the list of exported names
Real implementations are ordinary (strong) definitions elsewhere; the linker prefers them over the weak stubs.
"""
import os, sys
import xml.etree.ElementTree as ET

xml_path, out = sys.argv[1], sys.argv[2]
max_ver = tuple(int(x) for x in (sys.argv[3] if len(sys.argv) > 3 else "4.5").split("."))
root = ET.parse(xml_path).getroot()


def text_of(el):
    return "".join(el.itertext()).strip()


# Commands: name -> (proto text, [param text])
commands = {}
for cmd in root.find("commands"):
    proto = cmd.find("proto")
    name = proto.find("name").text
    ret = "".join(proto.itertext())[: -len(name)].strip()
    params = [" ".join(text_of(p).split()) for p in cmd.findall("param")]
    commands[name] = (ret, params)

# Core profile up to max_ver: add <require>, drop <remove profile="core">
funcs, enums = [], []
for feat in root.findall("feature"):
    if feat.get("api") != "gl":
        continue
    ver = tuple(int(x) for x in feat.get("number").split("."))
    if ver > max_ver:
        continue
    for req in feat.findall("require"):
        if req.get("profile") not in (None, "core"):
            continue
        funcs += [c.get("name") for c in req.findall("command")]
        enums += [e.get("name") for e in req.findall("enum")]
    for rem in feat.findall("remove"):
        if rem.get("profile") in (None, "core"):
            gone = {c.get("name") for c in rem.findall("command")} | {e.get("name") for e in rem.findall("enum")}
            funcs = [f for f in funcs if f not in gone]
            enums = [e for e in enums if e not in gone]
funcs = list(dict.fromkeys(funcs))
enums = list(dict.fromkeys(enums))

# Enum values
values = {}
for grp in root.findall("enums"):
    for e in grp.findall("enum"):
        if e.get("api") in (None, "gl"):
            values.setdefault(e.get("name"), e.get("value"))

# Types: keep the plain typedefs the core functions need (skip khrplatform include and GLES-only bits)
types = []
for t in root.find("types"):
    if t.get("api") not in (None, "gl") or t.get("name") in ("khrplatform", "GLhandleARB"):
        continue
    s = "".join(t.itertext()).strip()
    if s.startswith("typedef"):
        types.append(s)

os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "mgl_gl.h"), "w") as f:
    f.write("/* Generated by gen_exports.py from Khronos gl.xml, OpenGL %d.%d core. Do not edit. */\n" % max_ver)
    f.write("#pragma once\n#include <stdint.h>\n#include <stddef.h>\n")
    f.write("typedef int8_t khronos_int8_t; typedef uint8_t khronos_uint8_t; typedef int16_t khronos_int16_t;\n")
    f.write("typedef uint16_t khronos_uint16_t; typedef int32_t khronos_int32_t; typedef int64_t khronos_int64_t;\n")
    f.write("typedef uint64_t khronos_uint64_t; typedef float khronos_float_t; typedef intptr_t khronos_intptr_t;\n")
    f.write("typedef intptr_t khronos_ssize_t;\n")
    f.write("#define GLAPI __attribute__((visibility(\"default\")))\n#define APIENTRY\n#define GLAPIENTRY\n")
    for t in types:
        f.write(t + "\n")
    for e in enums:
        if e in values:
            f.write(f"#define {e} {values[e]}\n")
    for n in funcs:
        ret, params = commands[n]
        f.write(f"GLAPI {ret} {n}({', '.join(params) or 'void'});\n")

with open(os.path.join(out, "gl_stubs.c"), "w") as f:
    f.write("/* Generated by gen_exports.py. Weak stubs for every core entry point. Do not edit. */\n")
    f.write('#include "mgl_gl.h"\n#include "mgl_log.h"\n\n')
    for n in funcs:
        ret, params = commands[n]
        f.write(f"__attribute__((weak)) GLAPI {ret} {n}({', '.join(params) or 'void'})\n{{\n")
        f.write(f"    static int seen;\n    if (!seen) {{ seen = 1; mgl_unimplemented(\"{n}\"); }}\n")
        if ret != "void":
            f.write(f"    return ({ret})0;\n")
        f.write("}\n\n")

with open(os.path.join(out, "gl_functions.txt"), "w") as f:
    f.write("\n".join(funcs) + "\n")
print(f"OpenGL {max_ver[0]}.{max_ver[1]} core: {len(funcs)} functions, {len(enums)} enums")
